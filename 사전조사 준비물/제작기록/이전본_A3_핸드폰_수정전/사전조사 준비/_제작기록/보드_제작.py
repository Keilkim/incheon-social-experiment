def board(code, title, img, lines, w=6.2):
    W.page_break(d); W.h1(d, f"{code}  {title}")
    t = d.add_table(rows=1, cols=2); W._borders(t, "FFFFFF")
    W.fix_widths(t, [w + 0.4, 17.4 - w - 0.4])
    L, R_ = t.cell(0, 0), t.cell(0, 1)
    L.width = Cm(w + 0.4); R_.width = Cm(17.4 - w - 0.4); R_.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP
    L.paragraphs[0].add_run().add_picture(str(img), width=Cm(w))
    first = True
    for lab, txt in lines:
        p = R_.paragraphs[0] if first else R_.add_paragraph(); first = False
        p.paragraph_format.space_after = Pt(5)
        W._font(p.add_run(lab + "\n"), 8.6, True, W.TEAL); W.rich(p, txt, 9.6)


